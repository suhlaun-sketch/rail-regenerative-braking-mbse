function [yDouble, yInt32, yBoolean, internal_brake_demand_force, internal_regen_fade] = behavior(time_s, uDouble, uInt32, uBoolean)
%#codegen
in_brake_cylinder_pressure = uDouble(1);
in_brake_resistor_dissipated_power = uDouble(2);
in_dc_link_current = uDouble(3);
in_dc_link_voltage = uDouble(4);
in_dcdc_actual_power = uDouble(5);
in_dynamic_brake_force_request = uDouble(6);
in_ess_absorbed_power = uDouble(7);
in_ess_available_charge_power = uDouble(8);
in_ess_available_discharge_power = uDouble(9);
in_grid_acceptable_regenerative_power = uDouble(10);
in_grid_returned_power = uDouble(11);
in_line_current = uDouble(12);
in_line_voltage = uDouble(13);
in_main_reservoir_pressure = uDouble(14);
in_motor_speed = uDouble(15);
in_motor_torque_actual = uDouble(16);
in_regenerative_power_actual = uDouble(17);
in_service_brake_request = uDouble(18);
in_super_cap_soc = uDouble(19);
in_traction_command = uDouble(20);
in_ess_fault = uInt32(1);
in_external_safety_system_state = uInt32(2);
in_hv_breaker_command = uInt32(3);
in_safety_brake_request = uInt32(4);
in_traction_converter_fault = uInt32(5);
in_train_direction_command = uInt32(6);
in_brake_availability = uBoolean(1);
in_emergency_brake_request = uBoolean(2);
in_ess_availability = uBoolean(3);
out_achieved_dynamic_brake_force = 0.0;
out_available_dynamic_brake_force = 0.0;
out_brake_cylinder_pressure = 0.0;
out_brake_safety_loop_state = int32(0);
out_dcdc_enable_command = false;
out_dynamic_brake_availability = false;
out_emergency_brake_request = false;
out_ess_contactor_command = false;
out_ess_fault_reset_command = false;
out_ess_power_request = 0.0;
out_ess_precharge_command = false;
out_hv_safety_loop_state = int32(0);
out_main_reservoir_pressure = 0.0;
out_motor_torque_request = 0.0;
out_safety_brake_request = int32(0);
out_sanding_request = false;
out_service_brake_request = 0.0;
internal_brake_demand_force = 0.0;
internal_regen_fade = 0.0;
gear = 6.2000000000000002;
eta = 0.95999999999999996;
rw = 0.46000000000000002;
mass = 80000;
safety = (in_external_safety_system_state > 0) && (in_traction_converter_fault == 0);
brakeReq = max(0.0,in_service_brake_request);
if in_emergency_brake_request || in_safety_brake_request > 0, brakeReq = 1.2; end
v = abs(in_motor_speed)*rw/max(gear,1.0);
if ~(in_emergency_brake_request || in_safety_brake_request > 0) && (v <= 0.10000000000000001) && (brakeReq > 0.29999999999999999), brakeReq = 0.29999999999999999; end
Fmotor = 6000*gear*eta/rw;
Paccept = max(0.0,in_ess_available_charge_power)+max(0.0,in_grid_acceptable_regenerative_power);
xFade = min(1.0,max(0.0,(v-0.5)/(1.5-0.5)));
regenFade = xFade*xFade*(3.0-2.0*xFade);
Favail = regenFade*min(77000,min(Fmotor,Paccept/max(v,1.5)));
dynAvailable = safety && (in_ess_availability || in_grid_acceptable_regenerative_power > 0.0) && (in_super_cap_soc < 0.98) && (regenFade > 0.0);
if ~dynAvailable, Favail = 0.0; end
out_available_dynamic_brake_force = Favail;
out_dynamic_brake_availability = dynAvailable;
Trequest = 0.0;
if brakeReq > 0.0, Trequest = -min(6000,min(max(0.0,in_dynamic_brake_force_request),Favail)*rw/(gear*eta));
elseif safety && in_hv_breaker_command > 0 && in_dc_link_voltage >= 1200, Trequest = 4500*min(1.0,max(0.0,in_traction_command)); end
out_motor_torque_request = Trequest;
out_achieved_dynamic_brake_force = max(-in_motor_torque_actual*gear*eta/rw,0.0);
out_ess_power_request = min(max(0.0,in_regenerative_power_actual-in_grid_returned_power),max(0.0,in_ess_available_charge_power));
out_dcdc_enable_command = safety;
out_ess_contactor_command = safety;
out_ess_precharge_command = safety && (time_s < 1.0);
out_ess_fault_reset_command = ~safety;
out_emergency_brake_request = in_emergency_brake_request;
out_service_brake_request = brakeReq;
out_safety_brake_request = in_safety_brake_request;
out_brake_safety_loop_state = int32(safety);
out_hv_safety_loop_state = int32(safety);
out_sanding_request = (brakeReq > 0.8) && (v > 5.0);
out_brake_cylinder_pressure = in_brake_cylinder_pressure;
out_main_reservoir_pressure = in_main_reservoir_pressure;
internal_brake_demand_force = mass*brakeReq;
internal_regen_fade = regenFade;
yDouble = [out_achieved_dynamic_brake_force; out_available_dynamic_brake_force; out_brake_cylinder_pressure; out_ess_power_request; out_main_reservoir_pressure; out_motor_torque_request; out_service_brake_request];
yInt32 = [out_brake_safety_loop_state; out_hv_safety_loop_state; out_safety_brake_request];
yBoolean = [out_dcdc_enable_command; out_dynamic_brake_availability; out_emergency_brake_request; out_ess_contactor_command; out_ess_fault_reset_command; out_ess_precharge_command; out_sanding_request];
end